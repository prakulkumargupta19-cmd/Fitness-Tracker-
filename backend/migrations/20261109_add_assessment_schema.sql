-- Migration Script to Add Assessment Tables to Sports Schema

-- Create dynamic assessment fields for sports
CREATE TABLE IF NOT EXISTS sport_assessment_fields (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    sport_id BIGINT NOT NULL REFERENCES sports(id) ON DELETE CASCADE,
    field_key TEXT NOT NULL,
    field_label TEXT NOT NULL,
    field_type TEXT NOT NULL DEFAULT 'rating', -- possible values: 'number', 'text', 'rating'
    min_value NUMERIC,
    max_value NUMERIC,
    max_score NUMERIC NOT NULL DEFAULT 10,
    sort_order INTEGER NOT NULL DEFAULT 0,
    is_active BOOLEAN NOT NULL DEFAULT TRUE,
    created_at TIMESTAMP WITHOUT TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT uq_sport_assessment_fields_sport_key UNIQUE (sport_id, field_key)
);

-- Store student assessments for assigned sports
CREATE TABLE IF NOT EXISTS sport_student_assessments (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    student_id BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    sport_id BIGINT NOT NULL REFERENCES sports(id) ON DELETE CASCADE,
    coach_id BIGINT REFERENCES users(id) ON DELETE SET NULL,
    session_date DATE NOT NULL,
    attendance_status TEXT NOT NULL DEFAULT 'present' CHECK (
        attendance_status IN ('present', 'absent', 'late', 'excused')
    ),
    general_remarks TEXT,
    overall_score NUMERIC,
    created_at TIMESTAMP WITHOUT TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP WITHOUT TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT uq_sport_student_assessments_student_sport_date UNIQUE (
        student_id, sport_id, session_date
    )
);

-- Store scores associated with student assessments
CREATE TABLE IF NOT EXISTS sport_student_assessment_values (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    assessment_id BIGINT NOT NULL REFERENCES sport_student_assessments(id) ON DELETE CASCADE,
    field_key TEXT NOT NULL,
    score_value NUMERIC NOT NULL,
    CONSTRAINT uq_sport_assessment_values_assessment_key UNIQUE (assessment_id, field_key)
);

DROP TRIGGER IF EXISTS trg_sport_student_assessments_updated_at
    ON sport_student_assessments;
CREATE TRIGGER trg_sport_student_assessments_updated_at
    BEFORE UPDATE ON sport_student_assessments
    FOR EACH ROW
    EXECUTE FUNCTION set_updated_at();
