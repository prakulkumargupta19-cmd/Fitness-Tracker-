ALTER TABLE coaching_sessions ADD COLUMN IF NOT EXISTS session_type TEXT NOT NULL DEFAULT 'practice';
ALTER TABLE programmes ADD COLUMN IF NOT EXISTS assigned_dates INTEGER NOT NULL DEFAULT 5;

CREATE TABLE IF NOT EXISTS coaching_session_requests (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    programme_id BIGINT NOT NULL REFERENCES programmes(id) ON DELETE CASCADE,
    coach_id BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    session_date DATE NOT NULL,
    start_time TIME NOT NULL,
    end_time TIME NOT NULL,
    venue VARCHAR(255),
    notes TEXT,
    session_type TEXT NOT NULL CHECK (session_type IN ('practice','assessment')),
    status TEXT NOT NULL DEFAULT 'pending' CHECK (status IN ('pending','approved','rejected')),
    reviewed_by BIGINT REFERENCES users(id),
    reviewed_at TIMESTAMP WITHOUT TIME ZONE,
    created_at TIMESTAMP WITHOUT TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP
);