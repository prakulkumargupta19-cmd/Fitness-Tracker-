CREATE TABLE IF NOT EXISTS attendance_sessions (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    coach_id BIGINT NOT NULL
        REFERENCES users(id) ON DELETE CASCADE,
    sport_id BIGINT NOT NULL
        REFERENCES sports(id) ON DELETE CASCADE,
    session_date DATE NOT NULL,
    created_at TIMESTAMP WITHOUT TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,

    CONSTRAINT uq_coach_sport_date
        UNIQUE (coach_id, sport_id, session_date)
);


CREATE INDEX IF NOT EXISTS idx_session_date
    ON attendance_sessions (session_date);


CREATE TABLE IF NOT EXISTS attendance_records (
    session_id BIGINT NOT NULL
        REFERENCES attendance_sessions(id) ON DELETE CASCADE,

    student_id BIGINT NOT NULL
        REFERENCES users(id) ON DELETE CASCADE,

    status TEXT NOT NULL
        CHECK (status IN ('present', 'absent', 'late', 'excused')),

    session_date DATE NOT NULL,

    marked_by_role TEXT,
    marked_by_id BIGINT,

    updated_by_role TEXT,
    updated_by_id BIGINT,

    updated_at TIMESTAMP WITHOUT TIME ZONE NOT NULL
        DEFAULT CURRENT_TIMESTAMP,

    PRIMARY KEY (session_id, student_id)
);


CREATE INDEX IF NOT EXISTS idx_attendance_student_status
    ON attendance_records (student_id, status);


