-- ============================================================
-- STUDENT DETAILS VIEW
-- ============================================================

CREATE OR REPLACE VIEW student_details AS
SELECT
    u.id,
    u.full_name,
    u.email,
    u.contact_number,
    sp.date_of_birth,

    EXTRACT(
        YEAR FROM AGE(
            CURRENT_DATE,
            sp.date_of_birth
        )
    )::INTEGER AS age,

    sp.emergency_contact,
    sp.height_cm,
    sp.weight_kg,
    sp.department,
    sp.goal,
    sp.sport_activity

FROM users AS u

JOIN student_profiles AS sp
    ON sp.user_id = u.id

WHERE u.role = 'student';
