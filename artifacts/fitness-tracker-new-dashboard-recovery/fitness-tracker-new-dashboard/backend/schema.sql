-- Supabase PostgreSQL schema for Fitness Performance Tracker.
-- Apply this to a dedicated PostgreSQL database. Existing data must be exported
-- and migrated separately; this script does not delete application data.


CREATE TABLE IF NOT EXISTS users (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    role TEXT NOT NULL CHECK (role IN ('student', 'coach')),
    full_name VARCHAR(100) NOT NULL,
    email VARCHAR(150) NOT NULL UNIQUE,
    password_hash VARCHAR(255) NOT NULL,
    contact_number VARCHAR(30),
    is_verified BOOLEAN NOT NULL DEFAULT TRUE,
    coach_status TEXT,
    is_active BOOLEAN NOT NULL DEFAULT TRUE,
    coach_decided_at TIMESTAMP WITHOUT TIME ZONE,
    coach_decision_reason TEXT,
    last_login_at TIMESTAMP WITHOUT TIME ZONE,
    created_at TIMESTAMP WITHOUT TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,

    CONSTRAINT chk_coach_status CHECK (
        (
            role = 'coach'
            AND coach_status IS NOT NULL
            AND coach_status IN (
                'pending',
                'approved',
                'rejected',
                'declined'
            )
        )
        OR
        (
            role = 'student'
            AND coach_status IS NULL
        )
    )
);

CREATE TABLE IF NOT EXISTS dashboard_events (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    title VARCHAR(180) NOT NULL,
    description TEXT NOT NULL,
    event_date TIMESTAMP WITHOUT TIME ZONE NOT NULL,
    venue VARCHAR(255),
    created_by BIGINT,
    active BOOLEAN NOT NULL DEFAULT TRUE,
    created_at TIMESTAMP WITHOUT TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE IF NOT EXISTS coaching_session_requests (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    programme_id BIGINT NOT NULL REFERENCES programmes(id) ON DELETE CASCADE,
    coach_id BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    session_date DATE NOT NULL, start_time TIME NOT NULL, end_time TIME NOT NULL,
    venue VARCHAR(255), notes TEXT,
    session_type TEXT NOT NULL CHECK (session_type IN ('practice', 'assessment')),
    status TEXT NOT NULL DEFAULT 'pending' CHECK (status IN ('pending', 'approved', 'rejected')),
    reviewed_by BIGINT REFERENCES users(id), reviewed_at TIMESTAMP,
    created_at TIMESTAMP WITHOUT TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP
);

ALTER TABLE programmes ADD COLUMN IF NOT EXISTS assigned_dates INTEGER NOT NULL DEFAULT 5;
ALTER TABLE coaching_sessions ADD COLUMN IF NOT EXISTS session_type TEXT NOT NULL DEFAULT 'practice';

CREATE TABLE IF NOT EXISTS dashboard_event_registrations (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    event_id BIGINT NOT NULL REFERENCES dashboard_events(id) ON DELETE CASCADE,
    student_id BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    full_name VARCHAR(150) NOT NULL,
    email VARCHAR(150) NOT NULL,
    contact_number VARCHAR(30),
    registered_at TIMESTAMP WITHOUT TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    UNIQUE(event_id, student_id)
);

CREATE UNIQUE INDEX IF NOT EXISTS uq_users_email_lower
    ON users (LOWER(email));


CREATE TABLE IF NOT EXISTS student_profiles (
    user_id BIGINT PRIMARY KEY REFERENCES users(id) ON DELETE CASCADE,
    date_of_birth DATE NOT NULL,
    emergency_contact VARCHAR(30) NOT NULL,
    height_cm DECIMAL(5,2),
    weight_kg DECIMAL(5,2),
    goal VARCHAR(255),
    sport_activity VARCHAR(255),
    department VARCHAR(100),
    semester VARCHAR(40),
    gender VARCHAR(40),
    student_number VARCHAR(80),
    bio TEXT,
    blood_group VARCHAR(10),
    medical_history TEXT,
    address TEXT,
    parent_name VARCHAR(100),
    parent_phone VARCHAR(30),
    parent_address TEXT,
    passport_id VARCHAR(120),
    photo_path TEXT
);


CREATE TABLE IF NOT EXISTS otp_verifications (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    purpose TEXT NOT NULL CHECK (
        purpose IN (
            'signup',
            'login',
            'password_reset'
        )
    ),
    otp_hash VARCHAR(255) NOT NULL,
    expires_at TIMESTAMP WITHOUT TIME ZONE NOT NULL,
    attempt_count SMALLINT NOT NULL DEFAULT 0
        CHECK (attempt_count >= 0),
    is_used BOOLEAN NOT NULL DEFAULT FALSE,
    created_at TIMESTAMP WITHOUT TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP
);


CREATE INDEX IF NOT EXISTS idx_otp_user_purpose
    ON otp_verifications (user_id, purpose);


CREATE INDEX IF NOT EXISTS idx_otp_created_at
    ON otp_verifications (created_at);


CREATE TABLE IF NOT EXISTS pending_registrations (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    role TEXT NOT NULL CHECK (
        role IN ('student', 'coach')
    ),
    full_name VARCHAR(100) NOT NULL,
    email VARCHAR(150) NOT NULL UNIQUE,
    password_hash VARCHAR(255) NOT NULL,
    contact_number VARCHAR(30),
    otp_hash VARCHAR(255) NOT NULL,
    otp_expires_at TIMESTAMP WITHOUT TIME ZONE NOT NULL,
    otp_attempts SMALLINT NOT NULL DEFAULT 0
        CHECK (otp_attempts >= 0),
    otp_sent_at TIMESTAMP WITHOUT TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    otp_send_count SMALLINT NOT NULL DEFAULT 1
        CHECK (otp_send_count >= 0),
    status TEXT NOT NULL DEFAULT 'pending_verification'
        CHECK (
            status IN (
                'pending_verification',
                'pending_approval',
                'rejected',
                'declined'
            )
        ),
    created_at TIMESTAMP WITHOUT TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    verified_at TIMESTAMP WITHOUT TIME ZONE,
    decision_at TIMESTAMP WITHOUT TIME ZONE,
    decision_reason TEXT
);


CREATE UNIQUE INDEX IF NOT EXISTS uq_pending_registrations_email_lower
    ON pending_registrations (LOWER(email));


CREATE TABLE IF NOT EXISTS admins (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY
        (START WITH 1000000) PRIMARY KEY,
    full_name VARCHAR(100) NOT NULL,
    email VARCHAR(150) NOT NULL UNIQUE,
    password_hash VARCHAR(255) NOT NULL,
    is_verified BOOLEAN NOT NULL DEFAULT TRUE,
    last_login_at TIMESTAMP WITHOUT TIME ZONE,
    created_at TIMESTAMP WITHOUT TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP
);


CREATE UNIQUE INDEX IF NOT EXISTS uq_admins_email_lower
    ON admins (LOWER(email));


CREATE TABLE IF NOT EXISTS sports (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(50) NOT NULL UNIQUE
);


CREATE TABLE IF NOT EXISTS admin_otp_verifications (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    admin_id BIGINT NOT NULL
        REFERENCES admins(id) ON DELETE CASCADE,
    purpose TEXT NOT NULL CHECK (
        purpose IN ('login', 'password_reset')
    ),
    otp_hash VARCHAR(255) NOT NULL,
    expires_at TIMESTAMP WITHOUT TIME ZONE NOT NULL,
    attempt_count SMALLINT NOT NULL DEFAULT 0
        CHECK (attempt_count >= 0),
    is_used BOOLEAN NOT NULL DEFAULT FALSE,
    created_at TIMESTAMP WITHOUT TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP
);


CREATE INDEX IF NOT EXISTS idx_admin_otp_purpose
    ON admin_otp_verifications (admin_id, purpose);


