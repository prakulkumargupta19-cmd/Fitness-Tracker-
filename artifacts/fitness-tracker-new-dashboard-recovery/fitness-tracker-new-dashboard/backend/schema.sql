CREATE TABLE IF NOT EXISTS coach_sports (
    coach_id BIGINT NOT NULL
        REFERENCES users(id) ON DELETE CASCADE,
    sport_id BIGINT NOT NULL
        REFERENCES sports(id) ON DELETE CASCADE,
    assigned_by BIGINT NOT NULL
        REFERENCES admins(id),
    PRIMARY KEY (coach_id, sport_id)
);


CREATE TABLE IF NOT EXISTS student_sports (
    student_id BIGINT NOT NULL
        REFERENCES users(id) ON DELETE CASCADE,
    sport_id BIGINT NOT NULL
        REFERENCES sports(id) ON DELETE CASCADE,
    PRIMARY KEY (student_id, sport_id)
);


CREATE TABLE IF NOT EXISTS physical_assessments (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    student_id BIGINT NOT NULL
        REFERENCES users(id) ON DELETE CASCADE,
    coach_id BIGINT NOT NULL
        REFERENCES users(id) ON DELETE CASCADE,
    assessment_date DATE NOT NULL,
    speed DECIMAL(7,2),
    strength DECIMAL(7,2),
    endurance DECIMAL(7,2),
    agility DECIMAL(7,2),
    flexibility DECIMAL(7,2),
    reaction_time DECIMAL(7,2),
    overall_score DECIMAL(7,2),
    notes TEXT,
    created_at TIMESTAMP WITHOUT TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP WITHOUT TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP
);


CREATE INDEX IF NOT EXISTS idx_assessment_student_date
    ON physical_assessments (student_id, assessment_date);


CREATE TABLE IF NOT EXISTS training_sessions (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    student_id BIGINT NOT NULL
        REFERENCES users(id) ON DELETE CASCADE,
    coach_id BIGINT NOT NULL
        REFERENCES users(id) ON DELETE CASCADE,
    sport_id BIGINT NOT NULL
        REFERENCES sports(id),
    session_date DATE NOT NULL,
    training_type VARCHAR(100) NOT NULL,
    duration_minutes INTEGER NOT NULL,
    description TEXT,
    performance_notes TEXT,
    created_at TIMESTAMP WITHOUT TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP WITHOUT TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP
);


CREATE INDEX IF NOT EXISTS idx_training_student_date
    ON training_sessions (student_id, session_date);


CREATE TABLE IF NOT EXISTS goals (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    student_id BIGINT NOT NULL
        REFERENCES users(id) ON DELETE CASCADE,
    coach_id BIGINT NOT NULL
        REFERENCES users(id) ON DELETE CASCADE,
    title VARCHAR(150) NOT NULL,
    description TEXT,
    target_value DECIMAL(10,2),
    current_value DECIMAL(10,2),
    start_date DATE,
    target_date DATE,
    status TEXT NOT NULL DEFAULT 'active'
        CHECK (
            status IN (
                'active',
                'completed',
                'cancelled'
            )
        ),
    created_at TIMESTAMP WITHOUT TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP WITHOUT TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP
);


CREATE INDEX IF NOT EXISTS idx_goals_student_status
    ON goals (student_id, status);


CREATE TABLE IF NOT EXISTS coach_feedback (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    student_id BIGINT NOT NULL
        REFERENCES users(id) ON DELETE CASCADE,
    coach_id BIGINT NOT NULL
        REFERENCES users(id) ON DELETE CASCADE,
    feedback TEXT NOT NULL,
    rating SMALLINT CHECK (
        rating IS NULL OR rating >= 0
    ),
    created_at TIMESTAMP WITHOUT TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP WITHOUT TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP
);


CREATE INDEX IF NOT EXISTS idx_feedback_student_created
    ON coach_feedback (student_id, created_at);


