-- ============================================================
-- UPDATED_AT FUNCTION
-- ============================================================

CREATE OR REPLACE FUNCTION set_updated_at()
RETURNS TRIGGER
LANGUAGE plpgsql
AS $$
BEGIN
    NEW.updated_at = CURRENT_TIMESTAMP;
    RETURN NEW;
END;
$$;


DROP TRIGGER IF EXISTS trg_assessments_updated_at
    ON physical_assessments;


CREATE TRIGGER trg_assessments_updated_at
    BEFORE UPDATE ON physical_assessments
    FOR EACH ROW
    EXECUTE FUNCTION set_updated_at();


DROP TRIGGER IF EXISTS trg_training_sessions_updated_at
    ON training_sessions;


CREATE TRIGGER trg_training_sessions_updated_at
    BEFORE UPDATE ON training_sessions
    FOR EACH ROW
    EXECUTE FUNCTION set_updated_at();


