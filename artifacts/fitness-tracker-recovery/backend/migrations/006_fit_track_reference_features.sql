-- Fit-Track reference feature layer for the root PostgreSQL application.
-- This migration is additive and keeps the existing auth/session model intact.

ALTER TABLE sports ADD COLUMN IF NOT EXISTS activity_type VARCHAR(80) NOT NULL DEFAULT 'Activity';
ALTER TABLE sports ADD COLUMN IF NOT EXISTS venue VARCHAR(255);
ALTER TABLE sports ADD COLUMN IF NOT EXISTS cover_path TEXT;
ALTER TABLE sports ADD COLUMN IF NOT EXISTS is_active BOOLEAN NOT NULL DEFAULT TRUE;

ALTER TABLE student_profiles ADD COLUMN IF NOT EXISTS student_number VARCHAR(80);
ALTER TABLE student_profiles ADD COLUMN IF NOT EXISTS semester VARCHAR(40);
ALTER TABLE student_profiles ADD COLUMN IF NOT EXISTS bio TEXT;
ALTER TABLE student_profiles ADD COLUMN IF NOT EXISTS blood_group VARCHAR(20);
ALTER TABLE student_profiles ADD COLUMN IF NOT EXISTS medical_history TEXT;
ALTER TABLE student_profiles ADD COLUMN IF NOT EXISTS address TEXT;
ALTER TABLE student_profiles ADD COLUMN IF NOT EXISTS parent_name VARCHAR(120);
ALTER TABLE student_profiles ADD COLUMN IF NOT EXISTS parent_phone VARCHAR(30);
ALTER TABLE student_profiles ADD COLUMN IF NOT EXISTS parent_address TEXT;
ALTER TABLE student_profiles ADD COLUMN IF NOT EXISTS passport_id VARCHAR(120);
ALTER TABLE student_profiles ADD COLUMN IF NOT EXISTS photo_path TEXT;
CREATE UNIQUE INDEX IF NOT EXISTS uq_student_profiles_student_number
    ON student_profiles (student_number) WHERE student_number IS NOT NULL;
CREATE UNIQUE INDEX IF NOT EXISTS uq_student_profiles_passport_id
    ON student_profiles (passport_id) WHERE passport_id IS NOT NULL;

CREATE TABLE IF NOT EXISTS coach_profiles (
    user_id BIGINT PRIMARY KEY REFERENCES users(id) ON DELETE CASCADE,
    designation VARCHAR(120),
    photo_path TEXT,
    bio TEXT,
    created_at TIMESTAMP WITHOUT TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP WITHOUT TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE IF NOT EXISTS programmes (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(150) NOT NULL,
    sport_id BIGINT NOT NULL REFERENCES sports(id) ON DELETE RESTRICT,
    coach_id BIGINT REFERENCES users(id) ON DELETE SET NULL,
    schedule TEXT,
    venue VARCHAR(255),
    active BOOLEAN NOT NULL DEFAULT TRUE,
    created_at TIMESTAMP WITHOUT TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP WITHOUT TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE IF NOT EXISTS enrollments (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    student_id BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    programme_id BIGINT NOT NULL REFERENCES programmes(id) ON DELETE CASCADE,
    attendance INTEGER NOT NULL DEFAULT 0,
    total_sessions INTEGER NOT NULL DEFAULT 0,
    joined_on DATE NOT NULL DEFAULT CURRENT_DATE,
    status VARCHAR(40) NOT NULL DEFAULT 'Active',
    UNIQUE (student_id, programme_id)
);

CREATE TABLE IF NOT EXISTS attendance (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    enrollment_id BIGINT NOT NULL REFERENCES enrollments(id) ON DELETE CASCADE,
    session_date DATE NOT NULL,
    present BOOLEAN NOT NULL DEFAULT TRUE,
    UNIQUE (enrollment_id, session_date)
);

CREATE TABLE IF NOT EXISTS daily_assessments (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    enrollment_id BIGINT NOT NULL REFERENCES enrollments(id) ON DELETE CASCADE,
    coach_id BIGINT REFERENCES users(id) ON DELETE SET NULL,
    session_date DATE NOT NULL,
    attendance_status VARCHAR(30) NOT NULL DEFAULT 'Present',
    attendance_score INTEGER,
    skill_development INTEGER,
    passing INTEGER,
    dribbling INTEGER,
    shooting INTEGER,
    vision INTEGER,
    fitness INTEGER,
    overall_performance INTEGER,
    remarks TEXT,
    created_at TIMESTAMP WITHOUT TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP WITHOUT TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    UNIQUE (enrollment_id, session_date)
);

CREATE TABLE IF NOT EXISTS assessment_metric_scores (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    assessment_id BIGINT NOT NULL REFERENCES daily_assessments(id) ON DELETE CASCADE,
    metric_key VARCHAR(80) NOT NULL,
    metric_label VARCHAR(120) NOT NULL,
    score INTEGER NOT NULL CHECK (score BETWEEN 1 AND 10),
    UNIQUE (assessment_id, metric_key)
);

CREATE TABLE IF NOT EXISTS tournaments (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(180) NOT NULL,
    sport_id BIGINT NOT NULL REFERENCES sports(id) ON DELETE RESTRICT,
    start_date DATE NOT NULL,
    end_date DATE,
    venue VARCHAR(255),
    status VARCHAR(40) NOT NULL DEFAULT 'Upcoming',
    description TEXT,
    poster_path TEXT,
    registration_open BOOLEAN NOT NULL DEFAULT TRUE,
    created_at TIMESTAMP WITHOUT TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP WITHOUT TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE IF NOT EXISTS registrations (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tournament_id BIGINT NOT NULL REFERENCES tournaments(id) ON DELETE CASCADE,
    student_id BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    team_name VARCHAR(150),
    registration_status VARCHAR(40) NOT NULL DEFAULT 'Registered',
    registered_at TIMESTAMP WITHOUT TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    UNIQUE (tournament_id, student_id)
);

CREATE TABLE IF NOT EXISTS matches (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tournament_id BIGINT NOT NULL REFERENCES tournaments(id) ON DELETE CASCADE,
    round_name VARCHAR(100),
    match_date TIMESTAMP WITHOUT TIME ZONE,
    venue VARCHAR(255),
    category VARCHAR(80) NOT NULL DEFAULT 'Boys',
    team_a VARCHAR(150) NOT NULL,
    team_b VARCHAR(150) NOT NULL,
    score_a VARCHAR(30) NOT NULL DEFAULT '0',
    score_b VARCHAR(30) NOT NULL DEFAULT '0',
    status VARCHAR(40) NOT NULL DEFAULT 'Scheduled',
    photo_path TEXT,
    live_note TEXT,
    created_at TIMESTAMP WITHOUT TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP WITHOUT TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE IF NOT EXISTS achievements (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    student_id BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    title VARCHAR(180) NOT NULL,
    sport_id BIGINT REFERENCES sports(id) ON DELETE SET NULL,
    level VARCHAR(80),
    achievement_year VARCHAR(10),
    description TEXT,
    created_at TIMESTAMP WITHOUT TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE IF NOT EXISTS certificates (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    student_id BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    title VARCHAR(180) NOT NULL,
    issuer VARCHAR(150),
    issue_date DATE,
    certificate_no VARCHAR(100),
    file_path TEXT,
    created_at TIMESTAMP WITHOUT TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE IF NOT EXISTS messages (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    sender_user_id BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    receiver_user_id BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    message TEXT NOT NULL,
    created_at TIMESTAMP WITHOUT TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    read_at TIMESTAMP WITHOUT TIME ZONE
);

CREATE TABLE IF NOT EXISTS event_media (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tournament_id BIGINT REFERENCES tournaments(id) ON DELETE SET NULL,
    media_type VARCHAR(30) NOT NULL DEFAULT 'photo',
    file_path TEXT NOT NULL,
    caption TEXT,
    uploaded_by BIGINT REFERENCES users(id) ON DELETE SET NULL,
    created_at TIMESTAMP WITHOUT TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE IF NOT EXISTS match_live_stats (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    match_id BIGINT NOT NULL REFERENCES matches(id) ON DELETE CASCADE,
    stat_key VARCHAR(80) NOT NULL,
    stat_label VARCHAR(120) NOT NULL,
    stat_value TEXT,
    UNIQUE (match_id, stat_key)
);

CREATE TABLE IF NOT EXISTS event_participants (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tournament_id BIGINT NOT NULL REFERENCES tournaments(id) ON DELETE CASCADE,
    student_id BIGINT REFERENCES users(id) ON DELETE SET NULL,
    name VARCHAR(150) NOT NULL,
    department VARCHAR(120) NOT NULL,
    category VARCHAR(80) NOT NULL,
    year VARCHAR(20) NOT NULL,
    imported_at TIMESTAMP WITHOUT TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    UNIQUE (tournament_id, name, department, category, year)
);

CREATE TABLE IF NOT EXISTS match_players (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    match_id BIGINT NOT NULL REFERENCES matches(id) ON DELETE CASCADE,
    side VARCHAR(20) NOT NULL,
    student_name VARCHAR(150) NOT NULL,
    department VARCHAR(120),
    student_id BIGINT REFERENCES users(id) ON DELETE SET NULL
);

CREATE TABLE IF NOT EXISTS tournament_results (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tournament_id BIGINT NOT NULL REFERENCES tournaments(id) ON DELETE CASCADE,
    category VARCHAR(80) NOT NULL,
    winner VARCHAR(150) NOT NULL,
    runner_up VARCHAR(150) NOT NULL,
    notes TEXT,
    UNIQUE (tournament_id, category)
);

CREATE TABLE IF NOT EXISTS draw_documents (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tournament_id BIGINT NOT NULL REFERENCES tournaments(id) ON DELETE CASCADE,
    category VARCHAR(80) NOT NULL,
    format_type VARCHAR(30) NOT NULL,
    file_path TEXT NOT NULL,
    uploaded_by BIGINT REFERENCES users(id) ON DELETE SET NULL,
    created_at TIMESTAMP WITHOUT TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE IF NOT EXISTS announcements (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    title VARCHAR(180) NOT NULL,
    message TEXT NOT NULL,
    image_path TEXT,
    created_by BIGINT REFERENCES users(id) ON DELETE SET NULL,
    active BOOLEAN NOT NULL DEFAULT TRUE,
    created_at TIMESTAMP WITHOUT TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE IF NOT EXISTS certificate_templates (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tournament_id BIGINT NOT NULL REFERENCES tournaments(id) ON DELETE CASCADE,
    certificate_type VARCHAR(80) NOT NULL,
    file_path TEXT NOT NULL,
    uploaded_by BIGINT REFERENCES users(id) ON DELETE SET NULL,
    created_at TIMESTAMP WITHOUT TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    UNIQUE (tournament_id, certificate_type)
);

CREATE TABLE IF NOT EXISTS generated_certificates (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tournament_id BIGINT NOT NULL REFERENCES tournaments(id) ON DELETE CASCADE,
    participant_id BIGINT REFERENCES event_participants(id) ON DELETE SET NULL,
    student_id BIGINT REFERENCES users(id) ON DELETE SET NULL,
    certificate_type VARCHAR(80) NOT NULL,
    recipient_name VARCHAR(150) NOT NULL,
    achievement TEXT,
    certificate_no VARCHAR(120) NOT NULL UNIQUE,
    file_path TEXT NOT NULL,
    created_at TIMESTAMP WITHOUT TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE IF NOT EXISTS facility_media (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    sport_id BIGINT NOT NULL REFERENCES sports(id) ON DELETE CASCADE,
    file_path TEXT NOT NULL,
    caption TEXT,
    uploaded_by BIGINT REFERENCES users(id) ON DELETE SET NULL,
    created_at TIMESTAMP WITHOUT TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE IF NOT EXISTS coaching_sessions (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    programme_id BIGINT NOT NULL REFERENCES programmes(id) ON DELETE CASCADE,
    session_date DATE NOT NULL,
    start_time TIME NOT NULL,
    end_time TIME NOT NULL,
    venue VARCHAR(255),
    notes TEXT,
    status VARCHAR(40) NOT NULL DEFAULT 'Scheduled',
    created_by BIGINT REFERENCES users(id) ON DELETE SET NULL,
    updated_by BIGINT REFERENCES users(id) ON DELETE SET NULL,
    created_at TIMESTAMP WITHOUT TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP WITHOUT TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE INDEX IF NOT EXISTS idx_coaching_sessions_date ON coaching_sessions(session_date, start_time);
CREATE INDEX IF NOT EXISTS idx_coaching_sessions_programme ON coaching_sessions(programme_id, session_date);
CREATE INDEX IF NOT EXISTS idx_reference_matches_date ON matches(match_date);
CREATE INDEX IF NOT EXISTS idx_reference_messages_pair ON messages(sender_user_id, receiver_user_id, created_at);
CREATE INDEX IF NOT EXISTS idx_reference_media_tournament ON event_media(tournament_id, created_at);
